#!/usr/bin/env python3
"""
ota_sign.py: sign pebl weather firmware for over-the-air updates.

The device installs an update only if the manifest's ECDSA P-256 signature
verifies against the public key compiled into the firmware
(src/weather/ota_pubkey.h). What gets signed (must match ota.cpp):

    pebl-weather-ota/1\\n<version>\\n<size>\\n<sha256 hex of firmware.bin>\\n

Uses the openssl CLI only, so it runs the same on a Mac and in CI.

Commands:
  sign          firmware.bin + version + url  ->  manifest.json
  verify        manifest.json + firmware.bin against a public key (CI self-check)
  pubkey-header private key -> src/weather/ota_pubkey.h (run once per key)

Examples:
  python tools/ota_sign.py sign --firmware .pio/build/pebl_weather/firmware.bin \\
      --version 1.2.0 --url https://.../pebl-weather-1.2.0.bin \\
      --key ~/.pebl/ota_signing_key.pem --out manifest.json
  python tools/ota_sign.py verify --firmware fw.bin --manifest manifest.json \\
      --pubkey-header src/weather/ota_pubkey.h
  python tools/ota_sign.py pubkey-header --key ~/.pebl/ota_signing_key.pem

The private key never goes in the repo. In CI it comes from the
PEBL_OTA_SIGNING_KEY secret (pass --key-env PEBL_OTA_SIGNING_KEY).
"""
import argparse, base64, hashlib, json, os, re, subprocess, sys, tempfile

DOMAIN = "pebl-weather-ota/1"
SEMVER = re.compile(r"^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$")


def signed_message(version, size, sha_hex):
    return f"{DOMAIN}\n{version}\n{size}\n{sha_hex}\n".encode()


def openssl(*args, data=None):
    r = subprocess.run(["openssl", *args], input=data, capture_output=True)
    if r.returncode != 0:
        sys.exit(f"openssl {' '.join(args)} failed: {r.stderr.decode().strip()}")
    return r.stdout


def load_key_path(a, tmp):
    if a.key_env:
        pem = os.environ.get(a.key_env, "")
        if "PRIVATE KEY" not in pem:
            sys.exit(f"${a.key_env} is empty or not a PEM private key")
        path = os.path.join(tmp, "key.pem")
        with open(os.open(path, os.O_WRONLY | os.O_CREAT, 0o600), "w") as f:
            f.write(pem)
        return path
    if a.key:
        return os.path.expanduser(a.key)
    sys.exit("need --key or --key-env")


def cmd_sign(a):
    if not SEMVER.match(a.version):
        sys.exit(f"version '{a.version}' is not semver like 1.2.0 or 1.2.0-rc1")
    fw = open(a.firmware, "rb").read()
    sha = hashlib.sha256(fw).hexdigest()
    with tempfile.TemporaryDirectory() as tmp:
        key = load_key_path(a, tmp)
        sig = openssl("dgst", "-sha256", "-sign", key, data=signed_message(a.version, len(fw), sha))
    manifest = {"format": 1, "version": a.version, "url": a.url, "size": len(fw),
                "sha256": sha, "sig": base64.b64encode(sig).decode()}
    with open(a.out, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    print(f"signed {a.firmware} v{a.version} ({len(fw)} bytes, sha256 {sha[:16]}...) -> {a.out}")


def pubkey_pem_from_header(path):
    m = re.search(r'"(-----BEGIN PUBLIC KEY-----.*?-----END PUBLIC KEY-----\\n)"',
                  open(path).read(), re.S)
    if not m:
        sys.exit(f"no PEM public key found in {path}")
    return m.group(1).replace('\\n"\n    "', "\n").replace("\\n", "\n")


def cmd_verify(a):
    m = json.load(open(a.manifest))
    fw = open(a.firmware, "rb").read()
    sha = hashlib.sha256(fw).hexdigest()
    problems = []
    if m.get("format") != 1: problems.append("format != 1")
    if m.get("size") != len(fw): problems.append(f"size {m.get('size')} != {len(fw)}")
    if m.get("sha256") != sha: problems.append("sha256 mismatch")
    with tempfile.TemporaryDirectory() as tmp:
        pub = os.path.join(tmp, "pub.pem"); sigp = os.path.join(tmp, "sig.der")
        open(pub, "w").write(pubkey_pem_from_header(a.pubkey_header))
        open(sigp, "wb").write(base64.b64decode(m["sig"]))
        r = subprocess.run(["openssl", "dgst", "-sha256", "-verify", pub, "-signature", sigp],
                           input=signed_message(m["version"], len(fw), sha), capture_output=True)
        if r.returncode != 0: problems.append("signature does not verify with " + a.pubkey_header)
    if problems:
        sys.exit("VERIFY FAILED: " + "; ".join(problems))
    print(f"verified v{m['version']} ({len(fw)} bytes) against {a.pubkey_header}")


def cmd_pubkey_header(a):
    pem = openssl("ec", "-in", os.path.expanduser(a.key), "-pubout").decode()
    lines = "".join(f'    "{l}\\n"\n' for l in pem.strip().splitlines())
    out = ("#pragma once\n"
           "// Public half of the OTA signing key (ECDSA P-256). Generated by\n"
           "// tools/ota_sign.py pubkey-header. Safe to commit: it can only VERIFY.\n"
           "// The private key lives outside the repo (~/.pebl/ota_signing_key.pem and\n"
           "// the PEBL_OTA_SIGNING_KEY GitHub secret). Changing it means every device\n"
           "// needs one USB flash of a build that carries the new key.\n"
           f"static const char OTA_PUBKEY_PEM[] =\n{lines};\n")
    open(a.out, "w").write(out)
    print(f"wrote {a.out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sign")
    s.add_argument("--firmware", required=True); s.add_argument("--version", required=True)
    s.add_argument("--url", required=True); s.add_argument("--out", default="manifest.json")
    s.add_argument("--key"); s.add_argument("--key-env")
    v = sub.add_parser("verify")
    v.add_argument("--firmware", required=True); v.add_argument("--manifest", required=True)
    v.add_argument("--pubkey-header", default="src/weather/ota_pubkey.h")
    p = sub.add_parser("pubkey-header")
    p.add_argument("--key", required=True); p.add_argument("--out", default="src/weather/ota_pubkey.h")
    a = ap.parse_args()
    {"sign": cmd_sign, "verify": cmd_verify, "pubkey-header": cmd_pubkey_header}[a.cmd](a)


if __name__ == "__main__":
    main()
