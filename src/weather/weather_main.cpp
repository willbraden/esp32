// ----- HTTP helper -----
// One GET over a client the caller owns. The HTTPClient lives only in here, so
// it is always destroyed before the client: ~HTTPClient() calls stop() on its
// client whenever end() kept the connection for reuse, and a client destroyed
// first is a use-after-free. That was the long-standing "pbuf_free: p->ref > 0"
// crash: httpGet() used to declare the HTTPClient before a stack WiFiClient, so
// every plain-HTTP request ended by writing into freed heap memory, which lwIP
// tripped over moments later (netstress v3: 28 of 30 boots).
static String fetch(NetworkClient& client, const String& url, const char* what) {
    HTTPClient http;
    http.setReuse(false);   // one request per connection: end() really closes it
    String body;
    if (http.begin(client, url)) {
        http.setTimeout(9000);
        int code = http.GET();
        if (code == 200) body = http.getString();
        else Serial.printf("HTTP %d (%s) %s\n", code, what, url.c_str());
        http.end();
    }
    return body;
}

static String httpGet(const String& url, bool secure) {
    if (secure) {
        // Static: one TLS context for the life of the boot instead of a fresh
        // allocation per request.
        static WiFiClientSecure c;
        c.setCACertBundle(ca_bundle_start, ca_bundle_size());   // real cert validation
        String body = fetch(c, url, "secure");
        c.stop();
        return body;
    }
    WiFiClient c;
    return fetch(c, url, "plain");
}

// ----- data fetch -----
static bool getLocation(double& lat, double& lon, String& city) {
#if defined(HOME_LAT) && defined(HOME_LON)
    // IP geolocation lands on the ISP's hub, which put a Denver device in
    // Castle Rock: 18 miles south and ~800 ft higher, so a few degrees cold.
    lat = HOME_LAT; lon = HOME_LON; city = "home";
    return true;
#endif
    String body = httpGet("http://ip-api.com/json/?fields=status,lat,lon,city", false);
    if (body.isEmpty()) return false;
    JsonDocument doc;
    if (deserializeJson(doc, body)) return false;
    if (String(doc["status"] | "") != "success") return false;
    lat  = doc["lat"]  | 0.0;
    lon  = doc["lon"]  | 0.0;
    city = String((const char*)(doc["city"] | "Weather"));
    return true;
}

static String to12h(const String& hm) {        // "15:45" -> "3:45 PM"
    int colon = hm.indexOf(':');
    if (colon < 0) return hm;
    int h = hm.substring(0, colon).toInt();
    String m = hm.substring(colon + 1);
    const char* ap = (h >= 12) ? "PM" : "AM";
    int h12 = h % 12; if (h12 == 0) h12 = 12;
    return String(h12) + ":" + m + " " + ap;
}

// Three-letter weekday for a Gregorian date (Sakamoto's method).
static const char* weekdayAbbr(int y, int m, int d) {
    static const char* const names[] = {"SUN", "MON", "TUE", "WED", "THU", "FRI", "SAT"};
    static const int offs[] = {0, 3, 2, 5, 0, 3, 5, 1, 4, 6, 2, 4};
    if (m < 1 || m > 12 || d < 1 || d > 31) return "";
    if (m < 3) y--;
    return names[(y + y / 4 - y / 100 + y / 400 + offs[m - 1] + d) % 7];
}

static bool getWeather(double lat, double lon, Weather& w) {
    char url[320];
    snprintf(url, sizeof(url),
        "https://api.open-meteo.com/v1/forecast?latitude=%.4f&longitude=%.4f"
        "&current=temperature_2m,weather_code,is_day"
        "&daily=temperature_2m_max,temperature_2m_min"
        "&hourly=precipitation_probability,snowfall,weather_code&forecast_hours=6"
        "&temperature_unit=%s&timezone=auto&forecast_days=2",
        lat, lon, USE_FAHRENHEIT ? "fahrenheit" : "celsius");

    String body = httpGet(url, true);
    if (body.isEmpty()) return false;
    JsonDocument doc;
    if (deserializeJson(doc, body)) return false;

    w.temp = doc["current"]["temperature_2m"] | 0.0f;
    w.code = doc["current"]["weather_code"]    | 0;
    w.night = (doc["current"]["is_day"] | 1) == 0;   // missing -> day theme
    w.hi   = doc["daily"]["temperature_2m_max"][0] | 0.0f;
    w.lo   = doc["daily"]["temperature_2m_min"][0] | 0.0f;

    // Next 6 hours (the hourly window starts at the current hour).
    JsonArray pp = doc["hourly"]["precipitation_probability"];
    JsonArray sf = doc["hourly"]["snowfall"];
    JsonArray wc = doc["hourly"]["weather_code"];
    for (size_t i = 0; i < pp.size(); i++) {
        int p = pp[i] | 0;
        if (p > w.precipPct6h) w.precipPct6h = p;
        if ((sf[i] | 0.0f) > 0.0f || catOf(wc[i] | 0) == CAT_SNOW) w.snow6h = true;
    }

    String t = String((const char*)(doc["current"]["time"] | ""));  // "2026-06-13T15:45"
    int tpos = t.indexOf('T');
    w.updated = (tpos >= 0) ? to12h(t.substring(tpos + 1)) : "";
    // Weekday of the reading, shown so a stale screen (dead battery) is obvious.
    // Open-Meteo already returns location-local time (timezone=auto).
    if (tpos == 10)
        w.day = weekdayAbbr(t.substring(0, 4).toInt(), t.substring(5, 7).toInt(),
                            t.substring(8, 10).toInt());

    // "Tomorrow" for the night screen is the next day you wake up to: the next
    // date before midnight, but today's date in the small hours.
    int idx = (tpos >= 0 && t.substring(tpos + 1, tpos + 3).toInt() < 12) ? 0 : 1;
    w.tmrwHi = doc["daily"]["temperature_2m_max"][idx] | w.hi;
    w.tmrwLo = doc["daily"]["temperature_2m_min"][idx] | w.lo;
    String d = String((const char*)(doc["daily"]["time"][idx] | ""));   // "2026-06-14"
    if (d.length() == 10)
        w.tmrwDay = weekdayAbbr(d.substring(0, 4).toInt(), d.substring(5, 7).toInt(),
                                d.substring(8, 10).toInt());
    w.ok = true;
    return true;
}

// ----- icon drawing (filled black silhouettes) -----
static void drawSun(int cx, int cy, int r) {
    display.fillCircle(cx, cy, r, INK);
    for (int i = 0; i < 8; i++) {
        float a = i * PI / 4.0;
        int x1 = cx + cos(a) * (r + 4), y1 = cy + sin(a) * (r + 4);
        int x2 = cx + cos(a) * (r + 10), y2 = cy + sin(a) * (r + 10);
        display.drawLine(x1, y1, x2, y2, INK);
    }
}

static void drawCloud(int cx, int cy, int w) {
    int r1 = w * 0.20, r2 = w * 0.28, r3 = w * 0.22;
    display.fillCircle(cx - w * 0.26, cy,             r1, INK);
    display.fillCircle(cx - w * 0.02, cy - w * 0.12,  r2, INK);
    display.fillCircle(cx + w * 0.28, cy - w * 0.02,  r3, INK);
    display.fillRect(cx - w * 0.46, cy, w * 0.94, w * 0.22, INK);
}

static void drawIcon(int code, int bx, int by, int s) {
    // (bx,by) = center of an s-wide icon box
    switch (catOf(code)) {
        case CAT_CLEAR:
            drawSun(bx, by, s * 0.28);
            break;
        case CAT_PCLOUD:
            drawSun(bx - s * 0.16, by - s * 0.18, s * 0.18);
            drawCloud(bx + s * 0.05, by + s * 0.12, s * 0.8);
            break;
        case CAT_CLOUD:
            drawCloud(bx, by, s * 0.9);
            break;
        case CAT_FOG:
            drawCloud(bx, by - s * 0.12, s * 0.8);
            for (int i = 0; i < 3; i++)
                display.drawFastHLine(bx - s * 0.36, by + s * 0.18 + i * 6, s * 0.72, INK);
            break;
        case CAT_RAIN:
            drawCloud(bx, by - s * 0.14, s * 0.8);
            for (int i = -1; i <= 1; i++)
                display.drawLine(bx + i * 10, by + s * 0.16,
                                 bx + i * 10 - 4, by + s * 0.34, INK);
            break;
        case CAT_SNOW:
            drawCloud(bx, by - s * 0.14, s * 0.8);
            for (int i = -1; i <= 1; i++)
                display.fillCircle(bx + i * 11, by + s * 0.26, 2, INK);
            break;
        case CAT_STORM:
            drawCloud(bx, by - s * 0.14, s * 0.8);
            display.fillTriangle(bx, by + s * 0.10, bx - 8, by + s * 0.32,
                                 bx + 2, by + s * 0.30, INK);
            display.fillTriangle(bx + 2, by + s * 0.30, bx + 9, by + s * 0.30,
                                 bx + 1, by + s * 0.52, INK);
            break;
    }
}

