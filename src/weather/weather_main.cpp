// Word-mode rules. Precipitation wins when likely; otherwise the current temp
// (in °F) picks the word. Ranges are contiguous so every temperature has a word.
static const WordArt& wordArtFor(const Weather& w) {
    if (w.precipPct6h >= 50) return w.snow6h ? ART_SNOW : ART_RAIN;
    float f = USE_FAHRENHEIT ? w.temp : w.temp * 9.0f / 5.0f + 32.0f;
    int t = (int)lroundf(f);
    if (t < 32) return ART_FREEZE;
    if (t < 55) return ART_COLD;
    if (t < 70) return ART_CHILLY;
    if (t < 85) return ART_SHADES;
    if (t < 95) return ART_HOT;
    return ART_HELL;
}

// Inverted weekday bar on the left edge: white letters stacked top-to-bottom,
// each centred in the bar, the stack centred vertically. Mirrors day_layout()
// in tools/weather_design.py.
static void drawDayBar(const String& day, int barW, int capH, int gap) {
    int H = display.height();
    display.fillRect(0, 0, barW, H, INK);
    display.setFont(&WeatherDay);
    display.setTextColor(PAPER);
    int n = day.length();
    int top = (H - (n * capH + (n - 1) * gap)) / 2;
    for (int i = 0; i < n; i++) {
        char c[2] = {day[i], 0};
        int16_t bx, by; uint16_t bw, bh;
        display.getTextBounds(c, 0, 0, &bx, &by, &bw, &bh);
        display.setCursor((barW - (int)bw) / 2 - bx, top + i * (capH + gap) + capH);
        display.print(c);
    }
    display.setTextColor(INK);
}

// Weekday bar geometry, shared by both screens.
static const int BAR_W   = 19;   // inverted weekday bar (full height, left edge)
static const int DAY_CAP = 11;   // weekday letter cap height (= H_DAY in the tool)
static const int DAY_GAP = 8;    // gap between stacked weekday letters

static void renderWord(const Weather& w) {
    const WordArt& a = wordArtFor(w);
    // Centre in the word box (same maths as paste_art() in the tool).
    int x = WORD_BOX_X0 + (WORD_BOX_X1 - WORD_BOX_X0 - a.w) / 2;
    int y = WORD_BOX_Y0 + (WORD_BOX_Y1 - WORD_BOX_Y0 - a.h) / 2;
    display.setFullWindow();
    drawStart();
    display.firstPage();
    do {
        display.fillScreen(PAPER);
        drawDayBar(w.day, BAR_W, DAY_CAP, DAY_GAP);
        display.drawBitmap(x, y, a.bits, a.w, a.h, INK);
    } while (display.nextPage());
    drawDone(w.night && NIGHT_INVERT ? "word-night" : "word");
}

// Night screen: a small "Tomorrow" over the next day's low-high in the big
// current-temp font (the Hi/Lo font when a 3-digit temp makes that too wide),
// both centred in the box right of the bar. Mirrors tmrw_layout() in
// tools/weather_design.py.
static void renderTomorrow(const Weather& w) {
    const int H_LABEL = 17, H_BIG = 57, H_HL = 37;   // font heights (H_COND/H_BIG/H_HL in the tool)
    const int GAP = 10;                              // TMRW_GAP in the tool
    const int BOX_W = WORD_BOX_X1 - WORD_BOX_X0;
    int lo = (int)lroundf(w.tmrwLo), hi = (int)lroundf(w.tmrwHi);
    char range[16];
    // "46-63"; a slash once the low is negative, so "-5--2" can't happen
    snprintf(range, sizeof(range), lo < 0 ? "%d/%d" : "%d-%d", lo, hi);

    int16_t bx, by; uint16_t bw, bh;
    display.setFont(&WeatherBig);
    display.getTextBounds(range, 0, 0, &bx, &by, &bw, &bh);
    bool big = (int)bw <= BOX_W;
    int h = big ? H_BIG : H_HL;
    int labelBase = (display.height() - (H_LABEL + GAP + h)) / 2 + H_LABEL;
    int rangeBase = labelBase + GAP + h;

    display.setTextColor(INK);
    display.setFullWindow();
    drawStart();
    display.firstPage();
    do {
        display.fillScreen(PAPER);
        drawDayBar(w.tmrwDay, BAR_W, DAY_CAP, DAY_GAP);
        display.setFont(&WeatherCond);
        display.getTextBounds("Tomorrow", 0, 0, &bx, &by, &bw, &bh);
        display.setCursor(WORD_BOX_X0 + (BOX_W - (int)bw) / 2 - bx, labelBase);
        display.print("Tomorrow");
        display.setFont(big ? &WeatherBig : &WeatherHL);
        display.getTextBounds(range, 0, 0, &bx, &by, &bw, &bh);
        display.setCursor(WORD_BOX_X0 + (BOX_W - (int)bw) / 2 - bx, rangeBase);
        display.print(range);
    } while (display.nextPage());
    drawDone(NIGHT_INVERT ? "tomorrow-night" : "tomorrow");
}

static void renderWeather(const Weather& w) {
    int W = display.width();
    // ---- LAYOUT KNOBS (keep in sync with tools/weather_design.py) ----
    // Sized so the worst case (3-digit Hi next to a 3-digit current temp) keeps
    // 8px between them. Both columns are 84px tall and centred (y=19..103).
    const int LEFT_X    = BAR_W + 8;    // Hi/Lo are left-aligned to here
    const int RIGHT_X   = W - 8;        // current temp + condition are right-aligned to here
    const int HI_BASE   = 56;           // High baseline (top aligned with the big temp's top)
    const int LO_BASE   = 103;          // Low baseline  (aligned with the condition baseline)
    const int CUR_BASE  = 76;           // big current temp baseline (right; top level with Hi)
    const int COND_BASE = 103;          // condition word baseline (right)

    display.setTextColor(INK);
    display.setFullWindow();
    drawStart();
    display.firstPage();
    do {
        display.fillScreen(PAPER);
        int16_t bx, by; uint16_t bw, bh;

        // ---- weekday of this reading, so a stale screen (dead battery) is obvious ----
        drawDayBar(w.day, BAR_W, DAY_CAP, DAY_GAP);

        // ---- LEFT: High over Low, left-aligned ----
        display.setFont(&WeatherHL);
        display.setTextSize(1);
        drawTempAt((int)lroundf(w.hi), LEFT_X, HI_BASE);
        drawTempAt((int)lroundf(w.lo), LEFT_X, LO_BASE);

        // ---- RIGHT: big current temp, right-aligned ----
        display.setFont(&WeatherBig);
        display.setTextSize(1);
        char cbuf[8]; snprintf(cbuf, sizeof(cbuf), "%d", (int)lroundf(w.temp));
        display.getTextBounds(cbuf, 0, 0, &bx, &by, &bw, &bh);
        display.setCursor(RIGHT_X - bw - bx, CUR_BASE);
        display.print(cbuf);

        // ---- condition word, right-aligned under the temp ----
        display.setFont(&WeatherCond);
        const char* lab = shortLabelOf(w.code);
        display.getTextBounds(lab, 0, 0, &bx, &by, &bw, &bh);
        display.setCursor(RIGHT_X - bw - bx, COND_BASE);
        display.print(lab);
    } while (display.nextPage());
    drawDone(w.night && NIGHT_INVERT ? "numbers-night" : "numbers");
}

static void renderMessage(const char* line1, const char* line2) {
    int W = display.width(), H = display.height();
    setTheme(false);
    display.setTextColor(INK);
    display.setFullWindow();
    drawStart();
    display.firstPage();
    do {
        display.fillScreen(PAPER);
        display.drawRect(0, 0, W, H, INK);
        display.setFont(&FreeSansBold9pt7b);
        display.setCursor(12, 56);
        display.print(line1);
        if (line2) {
            display.setFont(&FreeSans9pt7b);
            display.setCursor(12, 82);
            display.print(line2);
        }
    } while (display.nextPage());
    drawDone("msg");
}

// ----- display bring-up -----
static void initDisplay() {
    pinMode(PIN_EPD_PWR, OUTPUT); digitalWrite(PIN_EPD_PWR, HIGH);
    delay(300);
    pinMode(PIN_EPD_CS,  OUTPUT); digitalWrite(PIN_EPD_CS, HIGH);
    pinMode(PIN_EPD_DC,  OUTPUT); digitalWrite(PIN_EPD_DC, LOW);
    pinMode(PIN_EPD_RST, OUTPUT); digitalWrite(PIN_EPD_RST, HIGH);
    pinMode(PIN_EPD_BUSY, INPUT);
    SPI.begin(PIN_EPD_SCLK, -1, PIN_EPD_MOSI, -1);
    // initial=false: skip GxEPD2's blank-to-white full refresh on first write.
    // Every update here is full-window, which writes both panel buffers
    // (writeImageForFullRefresh), so that extra clear only doubled the refresh.
    display.init(115200, false, 2, false);
    display.setRotation(3);   // landscape, flipped 180° from rotation 1
    display.epd2.setBusyCallback(onPanelBusy);
    // CS doubles as USER SW: a press during a refresh shorts the driven-high pin
    // to GND, so drive it as weakly as possible to bound that current.
    gpio_set_drive_capability(PIN_USER_SW, GPIO_DRIVE_CAP_0);
}

// ----- screen mode, persisted in NVS so it survives power-off -----
static Mode loadMode() {
    Preferences p;
    p.begin("pebl-weather", false);   // read-write so the namespace exists on first boot
    uint8_t m = p.getUChar("mode", MODE_NUMBERS);
    p.end();
    return m < MODE_COUNT ? (Mode)m : MODE_NUMBERS;
}

static void saveMode(Mode m) {
    Preferences p;
    p.begin("pebl-weather", false);
    p.putUChar("mode", m);
    p.end();
}

// At night the tomorrow screen replaces both screens, unless a short press
// asked to peek at the normal one.
static bool showTomorrow(bool night) { return NIGHT_TOMORROW && night && !rtc.nightPeek; }

static void render(const Weather& w, Mode m) {
    setTheme(w.night);
    if (showTomorrow(w.night)) renderTomorrow(w);
    else if (m == MODE_WORD) renderWord(w);
    else                renderWeather(w);
}

// ----- RTC cache of the last reading -----
static time_t nowSecs() {
    struct timeval tv;
    gettimeofday(&tv, nullptr);   // keeps counting through deep sleep
    return tv.tv_sec;
}

static void cacheStore(const Weather& w) {
    rtc.cache.valid = true;
    rtc.cache.fetchedAt = nowSecs();
    rtc.cache.temp = w.temp; rtc.cache.hi = w.hi; rtc.cache.lo = w.lo;
    rtc.cache.code = w.code; rtc.cache.precipPct6h = w.precipPct6h; rtc.cache.snow6h = w.snow6h;
    rtc.cache.night = w.night;
    strlcpy(rtc.cache.day, w.day.c_str(), sizeof(rtc.cache.day));
    rtc.cache.tmrwHi = w.tmrwHi; rtc.cache.tmrwLo = w.tmrwLo;
    strlcpy(rtc.cache.tmrwDay, w.tmrwDay.c_str(), sizeof(rtc.cache.tmrwDay));
}

static Weather cacheLoad() {
    Weather w;
    w.ok = true;
    w.temp = rtc.cache.temp; w.hi = rtc.cache.hi; w.lo = rtc.cache.lo;
    w.code = rtc.cache.code; w.precipPct6h = rtc.cache.precipPct6h; w.snow6h = rtc.cache.snow6h;
    w.night = rtc.cache.night;
    w.day = rtc.cache.day;
    w.tmrwHi = rtc.cache.tmrwHi; w.tmrwLo = rtc.cache.tmrwLo;
    w.tmrwDay = rtc.cache.tmrwDay;
    return w;
}

// Deep-sleep until the next scheduled refresh or a USER SW press, whichever
// comes first.
static void sleepUntilNext(uint32_t seconds) {
    // Still unconfirmed? Then this boot failed its OTA trial. Deep sleep won't
    // roll it back (the bootloader skips that on a wake), so count it here and
    // roll back once the update has had its MAX_TRIAL_BOOTS chances.
    if (int failed = ota::recordFailedTrial()) {
        char n[24];
        snprintf(n, sizeof(n), "trial-failed-%d/%d", failed, ota::MAX_TRIAL_BOOTS);
        bootlog::note(n);
        if (failed >= ota::MAX_TRIAL_BOOTS) {
            bootlog::note("self-rollback");
            ota::rollBack();
        }
    }
    display.hibernate();
    WiFi.disconnect(true, false);   // power down radio cleanly before sleep
    WiFi.mode(WIFI_OFF);
    // Hand the shared CS line back to the button, and wait for it to be released:
    // the wake is level-triggered, so a held button would wake us straight away.
    pinMode(PIN_USER_SW, INPUT);
    uint32_t t0 = millis();
    while (digitalRead(PIN_USER_SW) == LOW && millis() - t0 < 5000) delay(10);
    esp_sleep_enable_ext0_wakeup(PIN_USER_SW, 0);
    esp_sleep_enable_timer_wakeup((uint64_t)seconds * 1000000ULL);
    bootlog::stage("sleep");
    Serial.printf("Sleeping %lus (or until USER SW)...\n", (unsigned long)seconds);
    Serial.flush();
    esp_deep_sleep_start();
}

static void sleepAndRepeat() { sleepUntilNext(REFRESH_MINUTES * 60); }

// Fast, direct WiFi reconnect using the credentials saved in NVS (set during
// first-time QR provisioning). Returns true if connected within the timeout.
// This avoids WiFiManager's captive portal blocking for minutes on a wake.
static bool connectWiFiDirect(uint32_t timeoutMs) {
    WiFi.persistent(true);
    WiFi.mode(WIFI_STA);
    WiFi.begin();                   // reuse stored SSID/password
    uint32_t start = millis();
    while (WiFi.status() != WL_CONNECTED && (millis() - start) < timeoutMs) {
        delay(200);
    }
    bootlog::wifiMs(millis() - start);
    return WiFi.status() == WL_CONNECTED;
}

// How long USER SW is still held after an ext0 wake (the pin is left in RTC
// mode by the wake, so hand it back to the digital GPIO matrix first).
static uint32_t buttonHeldMs() {
    rtc_gpio_deinit(PIN_USER_SW);
    pinMode(PIN_USER_SW, INPUT);
    uint32_t t0 = millis();
    while (digitalRead(PIN_USER_SW) == LOW && millis() - t0 < LONG_PRESS_MS) delay(10);
    return millis() - t0;
}

// Did a person start this boot (power switch, RESET, a USB reset when
// flashing)? Only then may the WiFi setup portal open: it blocks for minutes,
// which must never happen unattended (a timer or button wake, a crash restart,
// or the restart after an OTA install).
static bool personStartedBoot() {
    switch (esp_reset_reason()) {
        case ESP_RST_POWERON: case ESP_RST_EXT: case ESP_RST_USB: return true;
        default: return false;
    }
}

// The first boot of an OTA update must fetch and draw to be confirmed, and a
// boot that gives up rolls the update back. So that boot retries a passing
// network problem instead of throwing a good update away.
static const int TRIAL_WIFI_TRIES  = 3;      // with 10 s, then 20 s, between them
static const int TRIAL_FETCH_TRIES = 2;      // 5 s apart

static bool connectWiFiWithRetries(int tries, bool trial) {
    for (int i = 0; i < tries; i++) {
        if (i) {
            Serial.printf("WiFi retry %d/%d\n", i + 1, tries);
            char n[16];
            snprintf(n, sizeof(n), "wifi-retry-%d", i + 1);
            bootlog::note(n);
            WiFi.disconnect(true, false);
            delay(10000 * i);
        }
#ifdef FAULT_TRIAL_WIFI_FAILS
        // Test images only (env pebl_weather_fault): fail the first N attempts
        // of an OTA trial boot, to prove the retry and rollback paths.
        if (trial && i < FAULT_TRIAL_WIFI_FAILS) {
            Serial.printf("FAULT: forcing WiFi attempt %d to fail\n", i + 1);
            bootlog::note("fault-wifi");
            continue;
        }
#endif
        if (connectWiFiDirect(WIFI_TIMEOUT_MS)) return true;
    }
    return false;
}

static void onOtaInstalling(const char* version) {
    char l2[48];
    snprintf(l2, sizeof(l2), "v%s -> v%s", FW_VERSION, version);
    char what[32];
    snprintf(what, sizeof(what), "installing-%s", version);
    bootlog::ota(what);
    renderMessage("Updating firmware...", l2);
}

static const char* otaResultName(ota::Result r) {
    switch (r) {
        case ota::Result::UpToDate:   return "up-to-date";
        case ota::Result::NoChannel:  return "no-channel";
        case ota::Result::SkippedBad: return "skipped-bad";
        case ota::Result::Failed:     return "failed";
    }
    return "?";
}

void setup() {
    Serial.begin(115200);
    delay(300);
    Serial.printf("\n=== pebl weather v%s ===\n", FW_VERSION);
    bool trial = ota::beginBoot();
    bootlog::begin(trial, ota::rolledBackFrom());
    rtcInit();
    // Just rolled back from a failed update: wait for the normal check schedule
    // (~2 h) before trying it again, so a passing problem can't use up all its
    // attempts in a few minutes. A long press still checks at once.
    if (ota::rolledBackFrom()) rtc.otaWakes = 0;

    esp_sleep_wakeup_cause_t wake = esp_sleep_get_wakeup_cause();
    bool timerWake  = (wake == ESP_SLEEP_WAKEUP_TIMER);
    bool buttonWake = (wake == ESP_SLEEP_WAKEUP_EXT0);
    bool attended   = personStartedBoot() && !trial;   // may block in the setup portal
    rtc.bootCount++;
    Serial.printf("Boot #%d  wake=%d %s%s\n", rtc.bootCount, (int)wake,
                  timerWake ? "(TIMER WAKE)" : buttonWake ? "(USER SW)" : attended ? "(power-on/reset)" : "(restart)",
                  trial ? " trial boot" : "");

    // USER SW: a short press flips to the other screen and remembers it; a long
    // press keeps the screen and forces a fresh fetch plus an update check.
    // At night a short press instead swaps between tomorrow and the normal
    // screen; the next timer wake or long press goes back to tomorrow.
    bool longPress = buttonWake && buttonHeldMs() >= LONG_PRESS_MS;
    Mode mode = loadMode();
    if (buttonWake && !longPress) {
        if (NIGHT_TOMORROW && rtc.cache.valid && rtc.cache.night) {
            rtc.nightPeek = !rtc.nightPeek;
        } else {
            mode = (Mode)((mode + 1) % MODE_COUNT);
            saveMode(mode);
        }
    } else {
        rtc.nightPeek = false;
    }
    if (longPress) { Serial.println("Long press: refresh + update check"); bootlog::longPress(); }
    Serial.printf("Mode %d%s\n", (int)mode, rtc.nightPeek ? " (night peek)" : "");

    initDisplay();

    // A press within the refresh window redraws from the cached reading (no
    // WiFi, so the screen flips in a few seconds) and keeps the original schedule.
    // Not on an unconfirmed update: it must fetch to prove itself, and a
    // cached redraw would end the boot without that.
    if (buttonWake && !longPress && rtc.cache.valid && !trial) {
        time_t age = nowSecs() - rtc.cache.fetchedAt;
        if (age >= 0 && age < REFRESH_MINUTES * 60 - 60) {
            Serial.printf("Redrawing cached reading (%lds old)\n", (long)age);
            render(cacheLoad(), mode);
            bootlog::stage("cache");
            sleepUntilNext(REFRESH_MINUTES * 60 - age);
        }
    }

    // Try a fast direct reconnect with saved creds first.
    if (!connectWiFiWithRetries(trial ? TRIAL_WIFI_TRIES : 1, trial)) {
        if (!attended) {
            // Unattended: never hang in a portal. Note it on screen and retry
            // next cycle (so we can SEE that the wake happened on battery).
            Serial.println("WiFi reconnect failed — retry next cycle");
            bootlog::fail("wifi");
            char l2[40];
            snprintf(l2, sizeof(l2), "wake #%d, retrying in %dm", rtc.bootCount, REFRESH_MINUTES);
            renderMessage("WiFi reconnecting...", l2);
            sleepAndRepeat();
        }
        // A person just started it: offer the provisioning portal.
        Serial.println("WiFi failed on a power-on/RESET — starting provisioning portal");
        bootlog::fail("wifi+portal");
        WiFiManager wm;
        wm.setConfigPortalTimeout(180);
        if (!wm.autoConnect("pebl-weather")) {
            bootlog::fail("wifi+portal-timeout");
            renderMessage("WiFi not connected", "Join 'pebl-weather' to set up");
            sleepAndRepeat();
        }
    }
    Serial.printf("WiFi OK: %s\n", WiFi.localIP().toString().c_str());
    bootlog::stage("wifi");

    int fetchTries = trial ? TRIAL_FETCH_TRIES : 1;
    double lat = 0, lon = 0; String city;
    bool located = false;
    for (int i = 0; i < fetchTries && !located; i++) {
        if (i) { Serial.println("Location retry"); bootlog::note("loc-retry"); delay(5000); }
        located = getLocation(lat, lon, city);
    }
    if (!located) {
        Serial.println("Location lookup failed");
        bootlog::fail("loc");
        renderMessage("Location error", "Will retry shortly");
        sleepAndRepeat();
    }
    Serial.printf("Loc: %s (%.4f, %.4f)\n", city.c_str(), lat, lon);
    bootlog::stage("loc");

    Weather w;
    bool fetched = false;
    for (int i = 0; i < fetchTries && !fetched; i++) {
        if (i) { Serial.println("Weather retry"); bootlog::note("weather-retry"); delay(5000); }
        fetched = getWeather(lat, lon, w);
    }
    if (!fetched) {
        Serial.println("Weather fetch failed");
        bootlog::fail("weather");
        renderMessage("Weather error", "Will retry shortly");
        sleepAndRepeat();
    }
    w.city = city;
    Serial.printf("Temp %.1f  Hi %.1f  Lo %.1f  code %d  precip6h %d%%%s  @ %s %s %s\n",
                  w.temp, w.hi, w.lo, w.code, w.precipPct6h, w.snow6h ? " (snow)" : "",
                  w.day.c_str(), w.updated.c_str(), w.night ? "night" : "day");
    Serial.printf("Tomorrow %s  Lo %.1f  Hi %.1f\n", w.tmrwDay.c_str(), w.tmrwLo, w.tmrwHi);

    bootlog::stage("weather");
    cacheStore(w);
    render(w, mode);
    bootlog::stage("drawn");

    // This image just fetched and drew successfully, so it can also fetch its
    // own next update: confirm it (cancels the bootloader's pending rollback).
    ota::confirmHealthy();

    if (longPress || ++rtc.otaWakes >= OTA_CHECK_EVERY_N_WAKES) {
        rtc.otaWakes = 0;
        bootlog::stage("ota");
        bootlog::ota(otaResultName(ota::checkAndInstall(onOtaInstalling)));   // restarts if it installs
    }
    sleepAndRepeat();
}

void loop() { /* never reached — deep sleep restarts setup() */ }
