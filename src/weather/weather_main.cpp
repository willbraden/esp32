// =============================================================================
// pebl ESP32-S3 — Weather Display
// =============================================================================
// A self-contained weather-station firmware for the pebl.ink board's
// DEPG0213BN (SSD1680) 2.13" e-ink display.
//
//   * Reuses the WiFi credentials already provisioned on the device (falls back
//     to a captive-portal "pebl-weather" AP if none are saved).
//   * Uses the fixed HOME_LAT/HOME_LON when the build sets them (platformio.ini),
//     else locates itself by IP (ip-api.com), which can be miles off.
//   * Fetches current conditions + daily high/low from Open-Meteo (free, no key).
//   * Renders a clean weather card, then deep-sleeps REFRESH_MINUTES and repeats.
//   * USER SW (GPIO16, shared with the display's CS line) toggles between the
//     numbers screen and a one-word screen (SNOW / RAIN / FREEZE / COLD / CHILLY /
//     sunglasses / HOT / HELL). The choice is saved in NVS. Holding it ~2 s
//     forces a fresh fetch and an update check instead.
//   * Between sunset and sunrise both screens give way to tomorrow's low-high
//     ("Tomorrow / 46-63"); a short press peeks at the normal screen.
//   * Updates itself over WiFi from signed GitHub releases (see ota.h).
//
// Build: env `pebl_weather` (board esp32-s3-devkitc-1). Confirmed display pins
// are below — see EINK_PIN_DISCOVERY.md for the reverse-engineering story.
// =============================================================================

